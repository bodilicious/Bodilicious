/**
 * Generates downsized WebP variants of the static product images.
 *
 * public/products/*.webp are ~1066×1600 (~63 KB). Product cards render them at
 * ~300 CSS px and cart/order thumbnails at 48–112 px, yet every one downloaded the
 * full original — the largest share of the storefront's bandwidth. This writes:
 *
 *   public/products/w560/<name>.webp   (product cards; 560 px covers 2–3x DPR)
 *   public/products/w240/<name>.webp   (thumbnails)
 *
 * and src/generated/imageVariants.ts listing the files that have variants. The
 * frontend only points at a variant listed there (utils/productImage.ts), so a
 * missing variant can never produce a broken image.
 *
 * Uses Puppeteer (already a devDependency for prerendering) — headless Chrome
 * resizes on a canvas and re-encodes WebP — so no image library is needed.
 * Incremental: a variant newer than its source is skipped. Never fails the build:
 * on any error it logs and exits 0, and the site keeps using the originals.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SRC_DIR = path.join(ROOT, "public", "products");
const MANIFEST = path.join(ROOT, "src", "generated", "imageVariants.ts");
const WIDTHS = [560, 240];
const QUALITY = 0.8;

// On CI/Render every file has its checkout time as mtime, so comparing mtimes there
// would regenerate committed variants for nothing — only build the missing ones.
const ON_CI = !!(process.env.CI || process.env.RENDER);
const isFresh = (variant, source) =>
  fs.existsSync(variant) && (ON_CI || fs.statSync(variant).mtimeMs >= fs.statSync(source).mtimeMs);

async function main() {
  if (!fs.existsSync(SRC_DIR)) return;
  const files = fs.readdirSync(SRC_DIR).filter(f => /\.(webp|png|jpe?g)$/i.test(f));
  for (const w of WIDTHS) fs.mkdirSync(path.join(SRC_DIR, `w${w}`), { recursive: true });

  const todo = files.filter(f => WIDTHS.some(w => !isFresh(path.join(SRC_DIR, `w${w}`, f.replace(/\.\w+$/, ".webp")), path.join(SRC_DIR, f))));

  if (todo.length) {
    const { default: puppeteer } = await import("puppeteer");
    const browser = await puppeteer.launch({
      headless: true,
      args: ["--no-sandbox", "--disable-setuid-sandbox", "--disable-dev-shm-usage", "--disable-gpu"],
    });
    try {
      const page = await browser.newPage();
      for (const file of todo) {
        const src = path.join(SRC_DIR, file);
        const mime = file.endsWith(".png") ? "image/png" : /\.jpe?g$/i.test(file) ? "image/jpeg" : "image/webp";
        const dataUrl = `data:${mime};base64,${fs.readFileSync(src).toString("base64")}`;
        const outputs = await page.evaluate(async (dataUrl, widths, quality) => {
          const img = new Image();
          img.src = dataUrl;
          await img.decode();
          return widths.map((w) => {
            if (img.naturalWidth <= w) return null; // never upscale
            const h = Math.round(img.naturalHeight * (w / img.naturalWidth));
            const canvas = document.createElement("canvas");
            canvas.width = w;
            canvas.height = h;
            const ctx = canvas.getContext("2d");
            ctx.imageSmoothingQuality = "high";
            ctx.drawImage(img, 0, 0, w, h);
            return canvas.toDataURL("image/webp", quality);
          });
        }, dataUrl, WIDTHS, QUALITY);

        WIDTHS.forEach((w, i) => {
          const out = path.join(SRC_DIR, `w${w}`, file.replace(/\.\w+$/, ".webp"));
          if (outputs[i]) fs.writeFileSync(out, Buffer.from(outputs[i].split(",")[1], "base64"));
          else fs.copyFileSync(src, out); // already small: reuse the original bytes
        });
      }
    } finally {
      await browser.close();
    }
  }

  // Manifest: originals that have every variant, regardless of whether this run made them.
  const withVariants = files.filter(f => WIDTHS.every(w => fs.existsSync(path.join(SRC_DIR, `w${w}`, f.replace(/\.\w+$/, ".webp")))));
  fs.mkdirSync(path.dirname(MANIFEST), { recursive: true });
  fs.writeFileSync(MANIFEST,
    "// AUTO-GENERATED by scripts/generate-image-variants.mjs — do not edit.\n" +
    `export const IMAGE_VARIANT_WIDTHS = ${JSON.stringify(WIDTHS)} as const;\n` +
    `export const IMAGE_VARIANT_FILES: ReadonlySet<string> = new Set(${JSON.stringify(withVariants.sort())});\n`);

  const sum = (dir) => fs.readdirSync(dir).reduce((s, f) => s + fs.statSync(path.join(dir, f)).size, 0);
  const orig = files.reduce((s, f) => s + fs.statSync(path.join(SRC_DIR, f)).size, 0);
  console.log(`[image-variants] ${todo.length} generated, ${withVariants.length}/${files.length} with variants. ` +
    `originals ${(orig / 1048576).toFixed(1)} MB → ` + WIDTHS.map(w => `w${w} ${(sum(path.join(SRC_DIR, `w${w}`)) / 1048576).toFixed(1)} MB`).join(", "));
}

main().catch((err) => {
  console.error("[image-variants] skipped:", err.message);
  process.exit(0); // never fail the build — the site falls back to the originals
});
